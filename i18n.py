def get_current_language() -> str:
    """Returns the currently active language code from st.session_state or fallback to 'en'."""
    try:
        if hasattr(st, "session_state") and "lang" in st.session_state:
            return st.session_state["lang"]
    except Exception:
        pass
    return "en"


def t(key: str, lang: Optional[str] = None, **kwargs) -> str:
    """
    Translates a key into the active or requested language.
    Guarantees English fallback on missing keys. Supports string interpolation.
    """
    target_lang = lang or get_current_language()
    
    # 1. Lookup in active target language
    lang_dict = TRANSLATIONS.get(target_lang, {})
    text = lang_dict.get(key)

    # 2. Fallback to English if key is missing in target language
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key, key)

    # 3. Apply string format substitutions if provided
    if kwargs:
        subs = dict(kwargs)
        if "id" in subs:
            subs.setdefault("record_id", subs["id"])
        if "record_id" in subs:
            subs.setdefault("id", subs["record_id"])
        try:
            return text.format(**subs)
        except Exception:
            return text

    return text


